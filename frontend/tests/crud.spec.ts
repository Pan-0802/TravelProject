import { test, expect } from '@playwright/test'

test('真实页面注册、修改昵称、修改密码及重新登录', async ({ page }) => {
  const username = `ui_profile_${Date.now()}`
  await page.goto('/auth/register')
  await page.getByPlaceholder('1-50 位，建议字母/数字/下划线').fill(username)
  await page.getByPlaceholder('最多 60 字').fill('资料验收')
  await page.getByPlaceholder('8-72 位', { exact: true }).fill('Profile@123456')
  await page.getByPlaceholder('请再次输入密码', { exact: true }).fill('Profile@123456')
  await page.getByRole('button', { name: '注册', exact: true }).click()
  await expect(page).toHaveURL(/\/auth\/login/)
  await page.getByPlaceholder('请输入密码', { exact: true }).fill('Profile@123456')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL(/\/trips$/)
  await page.goto('/profile')
  await page.getByPlaceholder('请输入新的昵称').fill('修改后的验收昵称')
  await page.getByRole('button', { name: '保存昵称', exact: true }).click()
  await expect(page.locator('.profile-name')).toHaveText('修改后的验收昵称')
  await page.getByPlaceholder('请输入当前密码').fill('Profile@123456')
  await page.getByPlaceholder('8-72 位', { exact: true }).fill('Changed@123456')
  await page.getByPlaceholder('请再次输入新密码').fill('Changed@123456')
  await page.getByRole('button', { name: '修改密码', exact: true }).click()
  await expect(page).toHaveURL(/\/auth\/login/)
  expect(await page.evaluate(() => sessionStorage.getItem('accessToken'))).toBeNull()
  await page.getByPlaceholder('请输入用户名').fill(username)
  await page.getByPlaceholder('请输入密码', { exact: true }).fill('Changed@123456')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL(/\/trips$/)
})

test('真实页面编辑删除行程消费和旅行，并验证跨用户隔离', async ({ page, request }) => {
  const username = `ui_crud_${Date.now()}`
  const password = 'Crud@123456'
  await request.post('/api/auth/register', { data: { username, password, confirmPassword: password } })
  const session = (await (await request.post('/api/auth/login', { data: { username, password } })).json()).data
  const headers = { Authorization: `Bearer ${session.accessToken}` }
  const trip = (await (await request.post('/api/trips', { headers, data: {
    title: 'CRUD独立验收旅行', destination: '重庆', startDate: '2026-12-01', endDate: '2026-12-01', totalBudget: 500
  } })).json()).data
  await request.post(`/api/trips/${trip.tripId}/days/2026-12-01/items`, { headers, data: { itemName: '待修改活动', estimatedCost: 0 } })
  await request.post(`/api/trips/${trip.tripId}/expenses`, { headers, data: { category: 'FOOD', amount: 20, spentOn: '2026-12-01', description: '待修改消费' } })
  await page.goto('/auth/login')
  await page.getByPlaceholder('请输入用户名').fill(username)
  await page.getByPlaceholder('请输入密码', { exact: true }).fill(password)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL(/\/trips$/)
  await page.goto(`/trips/${trip.tripId}`)
  await page.locator('.item__actions').getByRole('button', { name: '编辑', exact: true }).click()
  const itemDialog = page.getByRole('dialog', { name: '编辑行程项', exact: true })
  await itemDialog.getByPlaceholder('例如：解放碑步行游览').fill('修改后的活动')
  await itemDialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.locator('.item__name')).toContainText('修改后的活动')
  await page.locator('.item__actions').getByRole('button', { name: '删除', exact: true }).click()
  await page.getByRole('dialog', { name: '删除行程', exact: true }).getByRole('button', { name: '删除', exact: true }).click()
  await expect(page.locator('.item__actions')).toHaveCount(0)
  await page.getByRole('tab', { name: '消费记录' }).click()
  await page.locator('.expense-panel').getByRole('button',{name:'详情',exact:true}).click()
  await page.getByRole('dialog',{name:'消费详情',exact:true}).getByRole('button',{name:'编辑消费',exact:true}).click()
  const expenseDialog = page.getByRole('dialog', { name: '编辑消费', exact: true })
  await expenseDialog.getByRole('spinbutton').fill('35')
  await expenseDialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(expenseDialog).not.toBeVisible()
  await expect(page.locator('.expense-panel')).toContainText('¥35.00')
  await page.locator('.expense-panel').getByRole('button',{name:'详情',exact:true}).click()
  await page.getByRole('dialog',{name:'消费详情',exact:true}).getByRole('button',{name:'删除消费',exact:true}).click()
  await page.getByRole('dialog', { name: '删除消费', exact: true }).getByRole('button', { name: '删除', exact: true }).click()
  await expect(page.locator('.expense-panel')).not.toContainText('待修改消费')
  await page.getByRole('button', { name: '编辑旅行', exact: true }).click()
  const tripDialog = page.getByRole('dialog', { name: '编辑旅行', exact: true })
  await tripDialog.getByPlaceholder('例如：重庆三日游').fill('编辑后待删除旅行')
  await tripDialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page).toHaveURL(/\/trips$/)
  await page.getByRole('row').filter({hasText:'编辑后待删除旅行'}).getByRole('button',{name:'详情',exact:true}).click()
  await page.getByRole('button',{name:'删除旅行',exact:true}).click()
  await page.getByRole('dialog', { name: '删除旅行', exact: true }).getByRole('button', { name: '删除', exact: true }).click()
  await expect(page.getByText('编辑后待删除旅行', { exact: true })).toHaveCount(0)
  await page.goto('/trips/9')
  await expect(page.getByText('旅行不存在', { exact: true })).toBeVisible()
})
